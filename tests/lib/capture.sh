# shellcheck shell=bash
#
# 捕获一个可能失败的命令 —— **全仓只有这一种写法**。
#
# 用法（先 `. "$REPO/tests/lib/capture.sh"`）：
#     capture    some_cmd args…            # 读 $CAPTURE_OUT / $CAPTURE_RC
#     capture_ok "这一步在干嘛" some_cmd args…   # 顺带把「它跑成了没有」断言出来
#
# ── 为什么需要它 ───────────────────────────────────────────────────────────
#
# 场景脚本一律 `set -euo pipefail`。在那之下裸写 `VAR=$(cmd)`，`cmd` 一旦非 0
# 就**硬中止**：脚本从那一行直接退出，后面的判据一条都不跑，**连场景收尾那段
# 「XXX TESTS FAILED：N 条断言没过」的汇总（通常还带服务端日志与响应体转储）
# 也不会打印**。
#
# ⇒ 日志里剩下的是「非 0 退出 + 没有任何测试报告正文」，而按 `AGENTS.md` 的门禁
#   纪律，那个形态读作「**这条命令根本没跑起来**」。
#   ★ ★ ★ 于是**一个真实的产品回归会被读成 harness 坏了** —— 这两件事对代码的
#   含义完全相反，而它们在日志里长得一模一样。
#
# ⚠ 会踩到的恰恰都是本该报红的场景：读 `/stats` 的 python 走 `json.load`，
#   端点非 200 或少了字段时直接抛；exposition 解析器读到看不懂的行时按设计
#   `raise SystemExit`。**那正是这些判据存在的理由，不是让整段判据消失的理由。**
#
# ★ 判据是「**下一个人新写一行捕获时，正确写法应当是最省事的那一种**」：
#   一个要靠人每次重新想起来的纪律，与不存在的纪律之间只隔着一次疏忽 ——
#   而在本批里，那次疏忽在写下这条教训的**同一笔提交**里就发生了。
#
# ⚠ `$CAPTURE_OUT` / `$CAPTURE_RC` 是全局，下一次 `capture` 会覆盖它们
#   ⇒ 调用方必须**立刻**读出来存进自己的变量。

CAPTURE_RC=0
CAPTURE_OUT=""

capture() {
  set +e
  CAPTURE_OUT=$("$@" 2>&1)
  CAPTURE_RC=$?
  set -e
}

# `capture` + 立刻把「取数命令自己跑成了没有」**断言出来**。
#
# ⚠ 不这么写的话，取数失败只会让 `$CAPTURE_OUT` 变成一段 traceback，再由下游的
#   数值断言报成一条「期望 2 实际 Traceback…」—— **那条红指向的是判据，而真正
#   坏掉的是取数**。⇒ 让 rc 自己成为一条判据，红起来指得准。
#
# ⚠ 它依赖调用方定义了 `fail`（各场景都有，语义一致：记一笔失败但**不**退出，
#   好让后续判据继续跑、收尾汇总照常打印）。
# $1 = 说明，其余 = 命令。
capture_ok() {
  local what="$1"
  shift
  capture "$@"
  [ "$CAPTURE_RC" -eq 0 ] || fail "$what：取数命令自己失败了（rc=$CAPTURE_RC）：$CAPTURE_OUT"
}
