# shellcheck shell=bash
#
# 捕獲一個可能失敗的命令 —— **全倉只有這一種寫法**。
#
# 用法（先 `. "$REPO/tests/lib/capture.sh"`）：
#     capture    some_cmd args…            # 讀 $CAPTURE_OUT / $CAPTURE_RC
#     capture_ok "這一步在幹嘛" some_cmd args…   # 順帶把「它跑成了沒有」斷言出來
#
# ── 為什麼需要它 ───────────────────────────────────────────────────────────
#
# 場景指令碼一律 `set -euo pipefail`。在那之下裸寫 `VAR=$(cmd)`，`cmd` 一旦非 0
# 就**硬中止**：指令碼從那一行直接退出，後面的判據一條都不跑，**連場景收尾那段
# 「XXX TESTS FAILED：N 條斷言沒過」的彙總（通常還帶伺服器端紀錄與回應體轉儲）
# 也不會列印**。
#
# ⇒ 紀錄裡剩下的是「非 0 退出 + 沒有任何測試報告正文」，而按 `AGENTS.md` 的門禁
#   紀律，那個形態讀作「**這條命令根本沒跑起來**」。
#   ★ ★ ★ 於是**一個真實的產品迴歸會被讀成 harness 壞了** —— 這兩件事對程式碼的
#   含義完全相反，而它們在紀錄裡長得一模一樣。
#
# ⚠ 會踩到的恰恰都是本該報紅的場景：讀 `/stats` 的 python 走 `json.load`，
#   端點非 200 或少了欄位時直接拋；exposition 解析器讀到看不懂的行時按設計
#   `raise SystemExit`。**那正是這些判據存在的理由，不是讓整段判據消失的理由。**
#
# ★ 判據是「**下一個人新寫一行捕獲時，正確寫法應當是最省事的那一種**」：
#   一個要靠人每次重新想起來的紀律，與不存在的紀律之間只隔著一次疏忽 ——
#   而在本批裡，那次疏忽在寫下這條教訓的**同一筆提交**裡就發生了。
#
# ⚠ `$CAPTURE_OUT` / `$CAPTURE_RC` 是全域，下一次 `capture` 會覆蓋它們
#   ⇒ 呼叫方必須**立刻**讀出來存進自己的變數。

CAPTURE_RC=0
CAPTURE_OUT=""

capture() {
  set +e
  CAPTURE_OUT=$("$@" 2>&1)
  CAPTURE_RC=$?
  set -e
}

# `capture` + 立刻把「取數命令自己跑成了沒有」**斷言出來**。
#
# ⚠ 不這麼寫的話，取數失敗只會讓 `$CAPTURE_OUT` 變成一段 traceback，再由下游的
#   數值斷言報成一條「期望 2 實際 Traceback…」—— **那條紅指向的是判據，而真正
#   壞掉的是取數**。⇒ 讓 rc 自己成為一條判據，紅起來指得準。
#
# ⚠ 它相依呼叫方定義了 `fail`（各場景都有，語義一致：記一筆失敗但**不**退出，
#   好讓後續判據繼續跑、收尾彙總照常列印）。
# $1 = 說明，其餘 = 命令。
capture_ok() {
  local what="$1"
  shift
  capture "$@"
  [ "$CAPTURE_RC" -eq 0 ] || fail "$what：取数命令自己失败了（rc=$CAPTURE_RC）：$CAPTURE_OUT"
}
